`default_nettype none

// Area-only fixture. All console memories are EXTERNAL INPUTS: no memory deadline,
// arbitration, video backend, CDC or board timing proof. Never flash this fixture.
module retro_area (
    input wire nes_clk, md_clk, z80_clk, snes_clk,
    input wire reset,
    input wire [1:0] select,
    input wire [63:0] nes_flags,
    input wire [11:0] pad,
    input wire [7:0] nes_cpu_data, nes_ppu_data,
    output wire [21:0] nes_cpu_addr, nes_ppu_addr,
    output wire nes_cpu_rd, nes_cpu_wr, nes_ppu_rd, nes_ppu_wr,
    output wire [7:0] nes_cpu_wrdata, nes_ppu_wrdata,
    output wire [5:0] nes_color,
    output wire [2:0] nes_emphasis,
    output wire [8:0] nes_cycle, nes_line,
    output wire [15:0] nes_sample,
    input wire md_loading, md_ack,
    input wire [23:0] md_rom_words,
    input wire [15:0] md_rdata,
    output wire [23:0] md_addr,
    output wire [15:0] md_wdata,
    output wire [1:0] md_be,
    output wire md_we, md_req,
    output wire [3:0] md_red, md_green, md_blue,
    output wire md_pixel, md_hs, md_vs, md_hde, md_vde, md_interlace, md_field,
    output wire [1:0] md_resolution,
    output wire [15:0] md_left, md_right,
    input wire [1:0] snes_map,
    input wire [7:0] snes_chip,
    input wire snes_pal,
    input wire [21:0] snes_rom_mask,
    input wire snes_save_enable,
    input wire [16:0] snes_save_mask,
    input wire ipl_clear, ipl_we,
    input wire [5:0] ipl_addr,
    input wire [7:0] ipl_data,
    input wire coeff_clear, coeff_we,
    input wire [8:0] coeff_addr,
    input wire [11:0] coeff_data,
    output wire ipl_ready, coeff_ready, snes_active,
    output wire [4:0] snes_unsupported,
    output wire [16:0] wram_addr, save_addr,
    output wire [15:0] aram_addr,
    output wire [21:0] rom_addr,
    output wire [7:0] wram_data, aram_data, save_data,
    input wire [7:0] wram_q, aram_q, rom_q, save_q,
    output wire wram_rd, wram_wr, aram_rd, aram_wr, rom_rd, save_rd, save_wr,
    output wire sysclk_f_ce, sysclk_r_ce, refresh,
    output wire [14:0] snes_rgb,
    output wire snes_pixel, snes_dot, snes_hs, snes_vs, snes_hde, snes_vde,
    output wire snes_highres, snes_field, snes_interlace, snes_v224,
    output wire [8:0] snes_x, snes_y,
    output wire [15:0] snes_left, snes_right,
    output wire snes_audio_ready
);
  retro_nes_core nes (
      .clk(nes_clk), .reset(reset || select != 1), .mapper_flags(nes_flags), .joy(pad[7:0]),
      .cpu_addr(nes_cpu_addr), .cpu_read(nes_cpu_rd), .cpu_write(nes_cpu_wr),
      .cpu_wdata(nes_cpu_wrdata), .cpu_rdata(nes_cpu_data), .ppu_addr(nes_ppu_addr),
      .ppu_read(nes_ppu_rd), .ppu_write(nes_ppu_wr), .ppu_wdata(nes_ppu_wrdata),
      .ppu_rdata(nes_ppu_data), .color(nes_color), .emphasis(nes_emphasis),
      .cycle(nes_cycle), .scanline(nes_line), .sample(nes_sample));
  retro_md_core md (
      .clk_master_i(md_clk), .clk_z80_i(z80_clk), .reset_i(reset || select != 2),
      .loading_i(md_loading), .pad1_i(pad), .pad2_i(pad), .rom_words_i(md_rom_words),
      .mem_addr_o(md_addr), .mem_wdata_o(md_wdata), .mem_be_o(md_be), .mem_we_o(md_we),
      .mem_req_o(md_req), .mem_ack_i(md_ack), .mem_rdata_i(md_rdata),
      .red_o(md_red), .green_o(md_green), .blue_o(md_blue), .pixel_ce_o(md_pixel),
      .hs_n_o(md_hs), .vs_n_o(md_vs), .hde_o(md_hde), .vde_o(md_vde),
      .interlace_o(md_interlace), .field_o(md_field), .resolution_o(md_resolution),
      .audio_left_o(md_left), .audio_right_o(md_right),
      .debug_m68k_addr_o(), .debug_vbus_addr_o());
  snes_console snes (
      .clk(snes_clk), .reset(reset), .console_reset(1'b0), .run(select == 3),
      .cfg_map(snes_map), .cfg_chip(snes_chip), .cfg_pal(snes_pal),
      .cfg_rom_mask(snes_rom_mask), .cfg_save_enable(snes_save_enable),
      .cfg_save_mask(snes_save_mask), .pad1(pad), .pad2(pad),
      .ipl_clear(ipl_clear), .ipl_we(ipl_we), .ipl_addr(ipl_addr), .ipl_data(ipl_data),
      .ipl_ready(ipl_ready), .coeff_clear(coeff_clear), .coeff_we(coeff_we),
      .coeff_addr(coeff_addr), .coeff_data(coeff_data), .coeff_ready(coeff_ready),
      .active(snes_active), .unsupported(snes_unsupported),
      .wram_addr(wram_addr), .wram_data(wram_data), .wram_rd(wram_rd), .wram_wr(wram_wr),
      .wram_q(wram_q), .aram_addr(aram_addr), .aram_data(aram_data), .aram_rd(aram_rd),
      .aram_wr(aram_wr), .aram_q(aram_q), .rom_addr(rom_addr), .rom_rd(rom_rd), .rom_q(rom_q),
      .save_addr(save_addr), .save_data(save_data), .save_rd(save_rd), .save_wr(save_wr),
      .save_q(save_q), .sysclk_f_ce(sysclk_f_ce), .sysclk_r_ce(sysclk_r_ce), .refresh(refresh),
      .rgb(snes_rgb), .pixel_ce(snes_pixel), .dotclk(snes_dot), .hs(snes_hs), .vs(snes_vs),
      .hde(snes_hde), .vde(snes_vde), .highres(snes_highres), .field(snes_field),
      .interlace(snes_interlace), .v224(snes_v224), .x(snes_x), .y(snes_y),
      .audio_l(snes_left), .audio_r(snes_right), .audio_ready(snes_audio_ready));
endmodule

`default_nettype wire
